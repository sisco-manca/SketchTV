"""Browser smoke/regression test. Requires Playwright and Chromium, not a TV."""
import json
import os
from pathlib import Path
import sys
import tempfile
import threading
import urllib.request
from http.server import ThreadingHTTPServer

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from preview import Handler
from playwright.sync_api import sync_playwright

def main():
    server=ThreadingHTTPServer(('127.0.0.1',0),Handler)
    thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
    base=f'http://127.0.0.1:{server.server_port}'
    try:
        with sync_playwright() as p:
            options={'headless':True,'args':['--no-sandbox']}
            if os.environ.get('CHROMIUM'):options['executable_path']=os.environ['CHROMIUM']
            browser=p.chromium.launch(**options)
            page=browser.new_page(viewport={'width':1600,'height':1050},device_scale_factor=1)
            errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
            remote=[];page.on('request',lambda r:remote.append(r.url) if not r.url.startswith(base) else None)
            page.goto(base);page.wait_for_function('() => document.querySelectorAll(".tile").length === 15')
            assert page.locator('#status').inner_text().startswith('✓')
            assert page.locator('.tile.clock').inner_text().find('Località')>=0
            # Explicit geometric focus graph is the same generated by the build validator.
            page.locator('.tile[data-index="3"]').focus();page.keyboard.press('ArrowRight')
            assert page.locator('.tile.selected').get_attribute('data-index')=='4'
            page.keyboard.press('Enter');assert page.locator('#detail').is_visible();page.locator('#closeDetail').click()
            # Change geometry through the editor, then export the same configuration.
            page.locator('#y').fill('612');page.get_by_role('button',name='Applica al progetto').click();page.wait_for_function("() => document.querySelectorAll('.tile')[4].style.top === '612px'")
            with page.expect_download() as info:page.get_by_role('button',name='Esporta JSON ↓').click()
            with tempfile.TemporaryDirectory() as d:
                f=Path(d)/'project.json';info.value.save_as(f);assert json.loads(f.read_text())['tiles'][4]['rect'][1]==612
            # A conflicting layout cannot be exported or overwrite the last valid preview.
            config=json.loads(page.locator('#config').input_value());config['tiles'][4]['rect']=config['tiles'][3]['rect']
            page.locator('#config').fill(json.dumps(config));page.wait_for_function('() => document.querySelector("#status").classList.contains("invalid")')
            assert page.locator('#export').is_disabled()
            assert page.locator('.tile[data-index="4"]').evaluate('(e)=>e.style.top')=='612px'
            page.locator('#import').set_input_files({'name':'project.json','mimeType':'application/json','buffer':(ROOT/'project.json').read_bytes()});page.wait_for_function('() => !document.querySelector("#export").disabled')
            # User-provided labels stay text, never executable HTML.
            config=json.loads((ROOT/'project.json').read_text());config['tiles'][3]['label']='<img src=x onerror=alert(1)>'
            page.locator('#config').fill(json.dumps(config));page.wait_for_function("() => document.querySelectorAll('.tile')[3].textContent.includes('<img')")
            assert page.locator('.tile[data-index="3"] img').count()==0
            assert not errors,errors
            assert not remote,remote
            page.locator('#import').set_input_files({'name':'project.json','mimeType':'application/json','buffer':(ROOT/'project.json').read_bytes()});page.wait_for_function("() => document.querySelectorAll('.tile')[3].textContent === 'App 1'")
            output=os.environ.get('PREVIEW_SCREENSHOT')
            if output:page.screenshot(path=output,full_page=True)
            page.set_viewport_size({'width':600,'height':1100});page.wait_for_timeout(100)
            assert page.locator('#viewport').evaluate('(e)=>e.getBoundingClientRect().right')<=600
            # Only whitelisted preview files can be read; no keystores or source tree.
            for path in ('/key.jks','/.git/config','/src/dev/sketchtv/home/MainActivity.java','/assets/../key.jks'):
                response=page.request.get(base+path);assert response.status==404,(path,response.status)
            assert page.request.get(base+'/project.json',headers={'Host':'example.invalid'}).status==403
            assert page.request.get(base+'/').headers.get('content-security-policy')
            denied=page.request.post(base+'/validate',data='{}',headers={'Origin':'https://example.invalid'});assert denied.status==403
            browser.close()
            print('PASS: browser rendering, remote navigation, editing/export, invalid config, text escaping, responsive viewport, privacy and local-only requests')
    finally:server.shutdown();server.server_close()
if __name__=='__main__':main()
